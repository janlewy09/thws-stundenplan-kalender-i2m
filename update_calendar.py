#!/usr/bin/env python3
"""Fetch the public THWS M2IV timetable and publish an iCalendar feed.

The parser targets the graphical HTML timetable generated by sked campus.
It intentionally fails closed when too few events are recognized, so a page
layout change is less likely to publish an empty or incomplete calendar.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from collections import defaultdict
from datetime import date, datetime, time, timedelta, timezone
from html import unescape
from pathlib import Path
from typing import Iterable
from zoneinfo import ZoneInfo

import requests
from bs4 import BeautifulSoup, Tag

SOURCE_URL = "https://business.thws.de/fileadmin/share/vlplan/M2IV%201%20WS%2026_27.html"
CALENDAR_NAME = "THWS M2IV – 1. Semester WS 2026/27"
TIMEZONE = ZoneInfo("Europe/Berlin")
DATE_LABEL_RE = re.compile(
    r"\b(?:Mo|Di|Mi|Do|Fr|Sa|So)\s*,?\s*(\d{1,2}\.\d{1,2}\.\d{2,4})\b",
    re.IGNORECASE,
)
TIME_RANGE_RE = re.compile(r"(?<!\d)(\d{1,2}:\d{2})\s*[-–]\s*(\d{1,2}:\d{2})(?:\s*Uhr)?")
SHORT_CODE_RE = re.compile(r"^[A-Z0-9][A-Z0-9_-]{1,7}$")
SITE_CODE_RE = re.compile(r"(?<!\w)(Frie|Mü)(?!\w)", re.IGNORECASE)
CANCEL_TEXT_RE = re.compile(
    r"\b(?:entfällt|entfallen|entfaellt|fällt\s+aus|faellt\s+aus|"
    r"abgesagt|ausgefallen|ausfall|canceled|cancelled)\b",
    re.IGNORECASE,
)
CANCEL_CLASS_RE = re.compile(r"(?:cancel|entfall|ausfall|absag|storno)", re.IGNORECASE)


def normalise(value: str) -> str:
    return re.sub(r"\s+", " ", value.replace("\xa0", " ")).strip()


def text_from_html(value: str) -> str:
    soup = BeautifulSoup(value, "html.parser")
    for hidden in soup.select("script, style, noscript"):
        hidden.decompose()
    return soup.get_text("\n", strip=True)


def parse_german_date(value: str) -> date | None:
    value = normalise(value)
    for fmt in ("%d.%m.%y", "%d.%m.%Y"):
        try:
            return datetime.strptime(value, fmt).date()
        except ValueError:
            continue
    return None


def table_rows(table: Tag) -> list[Tag]:
    """Return rows in a table without accidentally treating nested rows as siblings."""
    rows: list[Tag] = []
    direct_rows = table.find_all("tr", recursive=False)
    rows.extend(direct_rows)
    for section in table.find_all(["thead", "tbody", "tfoot"], recursive=False):
        rows.extend(section.find_all("tr", recursive=False))
    if rows:
        return rows
    # Unusual HTML can omit explicit table sections; use a conservative fallback.
    return table.find_all("tr", recursive=True)


def direct_cells(row: Tag) -> list[Tag]:
    cells = row.find_all(["td", "th"], recursive=False)
    if cells:
        return cells
    return row.find_all(["td", "th"], recursive=True)


def table_to_columns(table: Tag) -> list[list[str]]:
    """Expand rowspan/colspan into day columns, similar to the sked grid layout."""
    rows = table_rows(table)
    grid: list[list[str | None]] = [[] for _ in rows]

    for row_index, row in enumerate(rows):
        column_index = 0
        for cell in direct_cells(row):
            while column_index < len(grid[row_index]) and grid[row_index][column_index] is not None:
                column_index += 1
            try:
                rowspan = max(1, int(cell.get("rowspan", 1)))
            except (TypeError, ValueError):
                rowspan = 1
            try:
                colspan = max(1, int(cell.get("colspan", 1)))
            except (TypeError, ValueError):
                colspan = 1
            # Preserve the cell's own class/style as some timetable exports
            # signal cancellation or strike-through on the containing <td>.
            cell_html = str(cell)

            for rr in range(row_index, min(len(rows), row_index + rowspan)):
                while len(grid[rr]) < column_index + colspan:
                    grid[rr].append(None)
                for cc in range(column_index, column_index + colspan):
                    # Repeating spanned cells is intentional. Duplicates are removed later.
                    if grid[rr][cc] is None:
                        grid[rr][cc] = cell_html
            column_index += colspan

    width = max((len(row) for row in grid), default=0)
    columns: list[list[str]] = []
    for col_idx in range(width):
        columns.append([
            (grid[row_idx][col_idx] or "") if col_idx < len(grid[row_idx]) else ""
            for row_idx in range(len(grid))
        ])
    return columns


def location_like(line: str) -> bool:
    s = normalise(line)
    return bool(
        re.match(r"^(?:WÜ\s*-|E\s*:|WISO\b|Raum\s*:|Ort\s*:)", s, re.IGNORECASE)
        or re.search(r"\b(?:F|M)\.\d+\.\d+\b", s)
        or "Ort:" in s
    )


def is_cancelled_event(cell_html: str, visible_text: str) -> bool:
    """Recognise common textual and HTML styling markers for cancelled sessions.

    Events that are explicitly marked as cancelled are deliberately omitted from
    the generated subscription feed. When the calendar app refreshes the feed,
    the removed event can disappear from the subscribed calendar.
    """
    if CANCEL_TEXT_RE.search(visible_text):
        return True

    soup = BeautifulSoup(cell_html, "html.parser")
    for element in soup.find_all(True):
        classes = " ".join(str(c) for c in (element.get("class") or []))
        metadata = " ".join(
            str(element.get(attr, ""))
            for attr in ("title", "aria-label", "data-status", "data-state")
        )
        style = str(element.get("style", ""))
        if CANCEL_CLASS_RE.search(classes) or CANCEL_TEXT_RE.search(metadata):
            return True
        if re.search(r"text-decoration\s*:\s*[^;]*line-through", style, re.IGNORECASE):
            return True
        if element.name in {"del", "s", "strike"}:
            return True
    return False


def site_code_from_lines(lines: list[str], title_index: int, location: str) -> str | None:
    """Return the venue abbreviation shown by the source: 'Frie' or 'Mü'."""
    candidates = [location]
    candidates.extend(line for i, line in enumerate(lines) if i != title_index)
    for candidate in candidates:
        match = SITE_CODE_RE.search(candidate)
        if match:
            return "Mü" if match.group(1).casefold() == "mü" else "Frie"
    return None


def parse_event_cell(cell_html: str, event_date: date) -> dict | None:
    raw_text = text_from_html(cell_html)
    if not raw_text:
        return None
    # A cancelled event must not remain in the resulting calendar feed.
    if is_cancelled_event(cell_html, raw_text):
        return None

    time_match = TIME_RANGE_RE.search(raw_text)
    if not time_match:
        return None

    lines = [normalise(line) for line in raw_text.splitlines()]
    lines = [line for line in lines if line]
    # A few sked exports flatten line breaks. Split a line around a detected time range.
    matching_line_idx = next((i for i, line in enumerate(lines) if TIME_RANGE_RE.search(line)), None)
    if matching_line_idx is not None:
        line = lines[matching_line_idx]
        lines[matching_line_idx] = normalise(TIME_RANGE_RE.sub("", line, count=1))
        if not lines[matching_line_idx]:
            lines.pop(matching_line_idx)
        else:
            # The time is gone; all other text on that line remains available as metadata.
            pass
    else:
        lines = [normalise(TIME_RANGE_RE.sub("", line, count=1)) for line in lines]
        lines = [line for line in lines if line]

    # Remove only exact time strings from any line; leave teaching metadata intact.
    cleaned_lines: list[str] = []
    for line in lines:
        line = normalise(TIME_RANGE_RE.sub("", line))
        line = re.sub(r"\s*\[\d+\]\s*$", "", line).strip()
        if line and line not in cleaned_lines:
            cleaned_lines.append(line)

    # The time cell can appear anywhere in the source table due to rowspans.
    start_text, end_text = time_match.group(1), time_match.group(2)
    try:
        start_t = datetime.strptime(start_text, "%H:%M").time()
        end_t = datetime.strptime(end_text, "%H:%M").time()
    except ValueError:
        return None
    start_dt = datetime.combine(event_date, start_t, tzinfo=TIMEZONE)
    end_dt = datetime.combine(event_date, end_t, tzinfo=TIMEZONE)
    if end_dt <= start_dt:
        return None

    # Preferred title in THWS's current plan has a trailing [M2IV] marker.
    title_index = None
    for i, line in enumerate(cleaned_lines):
        if "[M2IV]" in line.upper():
            title_index = i
            break

    if title_index is None:
        for i, line in enumerate(cleaned_lines):
            if SHORT_CODE_RE.fullmatch(line) and line.upper() not in {"M2IV"}:
                continue
            if line.upper() in {"EXTERNE VERANSTALTUNG", "ONLINE-VERANSTALTUNG"}:
                continue
            if location_like(line):
                continue
            if len(re.sub(r"[^A-Za-zÄÖÜäöüß]", "", line)) >= 3:
                title_index = i
                break

    if title_index is None:
        return None

    title = re.sub(r"\s*\[M2IV\]\s*", "", cleaned_lines[title_index], flags=re.IGNORECASE).strip()
    title = normalise(title)
    title = re.sub(r"\s*\[\d+\]\s*$", "", title).strip()
    if not title or TIME_RANGE_RE.fullmatch(title):
        return None

    location = ""
    for line in reversed(cleaned_lines):
        if location_like(line):
            location = line
            break

    # The short venue code requested by the user (Frie/Mü) is shown after the
    # event title in Apple Calendar, while the full room remains in LOCATION.
    site_code = site_code_from_lines(cleaned_lines, title_index, location)
    display_title = f"{title} ({site_code})" if site_code else title

    module_code = next(
        (
            line for line in cleaned_lines
            if SHORT_CODE_RE.fullmatch(line) and line.upper() != "M2IV"
        ),
        "",
    )

    # Keep all other visible event details in the description so that we do not
    # accidentally discard lecturer, topic, online/external flags, or format notes.
    description_lines: list[str] = []
    for i, line in enumerate(cleaned_lines):
        if i == title_index or line == location:
            continue
        if SHORT_CODE_RE.fullmatch(line) and line.upper() != "M2IV":
            description_lines.append(f"Modulcode: {line}")
        elif line.upper() in {"EXTERNE VERANSTALTUNG", "ONLINE-VERANSTALTUNG"}:
            description_lines.append(line.title())
        else:
            description_lines.append(line)
    # Deduplicate while preserving order.
    description_lines = list(dict.fromkeys(description_lines))
    description = "\n".join(description_lines)

    return {
        "date": event_date.isoformat(),
        "start": start_dt,
        "end": end_dt,
        "title": display_title,
        # Keep the unsuffixed title for a stable UID when the venue changes
        # from Frie to Mü (or vice versa).
        "source_title": title,
        "site_code": site_code,
        "module_code": module_code,
        "location": location,
        "description": description,
    }


def parse_timetable(html_text: str) -> tuple[list[dict], str | None]:
    soup = BeautifulSoup(html_text, "html.parser")
    events: list[dict] = []
    seen: set[tuple] = set()
    date_columns_found = 0

    # Sked exports often contain one table per week; use all tables and all day columns.
    for table in soup.find_all("table"):
        for column in table_to_columns(table):
            day_date: date | None = None
            date_row_index = -1
            for idx, cell_html in enumerate(column):
                text = text_from_html(cell_html)
                match = DATE_LABEL_RE.search(text)
                if match:
                    day_date = parse_german_date(match.group(1))
                    date_row_index = idx
                    if day_date:
                        break
            if day_date is None:
                continue
            date_columns_found += 1
            for cell_html in column[date_row_index + 1:]:
                event = parse_event_cell(cell_html, day_date)
                if not event:
                    continue
                # Unique content keeps rowspans and duplicate date columns from multiplying events.
                signature = (
                    event["date"], event["start"].strftime("%H:%M"), event["end"].strftime("%H:%M"),
                    event["title"].casefold(), event["location"].casefold(), event["description"].casefold(),
                )
                if signature not in seen:
                    seen.add(signature)
                    events.append(event)

    events.sort(key=lambda e: (e["start"], e["end"], e["title"].casefold()))

    # The exported page includes a human-readable "Stand:" timestamp in its footer.
    page_text = soup.get_text(" ", strip=True)
    stand = None
    stand_match = re.search(r"Stand:\s*(\d{1,2}\.\d{1,2}\.\d{4})[, ]+\s*(\d{1,2}:\d{2})\s*Uhr", page_text, re.IGNORECASE)
    if stand_match:
        try:
            stand_dt = datetime.strptime(f"{stand_match.group(1)} {stand_match.group(2)}", "%d.%m.%Y %H:%M")
            stand = stand_dt.replace(tzinfo=TIMEZONE).isoformat()
        except ValueError:
            stand = None

    if date_columns_found == 0:
        raise RuntimeError("Keine Wochentage erkannt. Der THWS-/sked-Seitenaufbau könnte sich geändert haben.")
    return events, stand


def ics_escape(value: str) -> str:
    value = value.replace("\\", "\\\\").replace("\r\n", "\n").replace("\r", "\n")
    value = value.replace("\n", r"\n").replace(";", r"\;").replace(",", r"\,")
    return value


def fold_ics_line(line: str, max_bytes: int = 73) -> str:
    """Fold long iCalendar lines by UTF-8 byte length (RFC 5545)."""
    chunks: list[str] = []
    current = ""
    current_bytes = 0
    for char in line:
        size = len(char.encode("utf-8"))
        if current and current_bytes + size > max_bytes:
            chunks.append(current)
            current = " " + char
            current_bytes = 1 + size
        else:
            current += char
            current_bytes += size
    chunks.append(current)
    return "\r\n".join(chunks)


def ics_datetime(dt: datetime) -> str:
    return dt.astimezone(timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def build_ics(events: list[dict], source_stand: str | None) -> str:
    # Use the source's own last-modified timestamp as the feed stamp where available.
    # It remains stable between source changes, avoiding a needless rewrite each hour.
    if source_stand:
        stamp_dt = datetime.fromisoformat(source_stand).astimezone(timezone.utc)
    else:
        stamp_dt = datetime.now(timezone.utc)
    stamp = stamp_dt.strftime("%Y%m%dT%H%M%SZ")

    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//THWS M2IV timetable helper//DE",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        f"X-WR-CALNAME:{ics_escape(CALENDAR_NAME)}",
        "X-WR-TIMEZONE:Europe/Berlin",
        "REFRESH-INTERVAL;VALUE=DURATION:PT1H",
        "X-PUBLISHED-TTL:PT1H",
    ]

    used_uids: set[str] = set()
    for event in events:
        # Do not include the time in the UID: time changes on the same date can update
        # the existing event rather than creating an additional one.
        # Do not put time, venue, display suffix, or mutable description in the
        # UID. That lets calendar clients update the same session rather than
        # leaving an old event behind when its time/venue/details change.
        identity = "|".join((
            event["date"],
            event.get("source_title", event["title"]),
            event.get("module_code", ""),
        ))
        digest = hashlib.sha256(identity.encode("utf-8")).hexdigest()[:32]
        uid = f"{digest}@thws-m2iv-calendar"
        if uid in used_uids:
            # Rare fallback for same-day repeated sessions with identical text.
            digest = hashlib.sha256((identity + "|" + event["start"].isoformat()).encode("utf-8")).hexdigest()[:32]
            uid = f"{digest}@thws-m2iv-calendar"
        used_uids.add(uid)

        lines.extend([
            "BEGIN:VEVENT",
            f"UID:{uid}",
            f"DTSTAMP:{stamp}",
            f"LAST-MODIFIED:{stamp}",
            f"DTSTART:{ics_datetime(event['start'])}",
            f"DTEND:{ics_datetime(event['end'])}",
            f"SUMMARY:{ics_escape(event['title'])}",
        ])
        if event["location"]:
            lines.append(f"LOCATION:{ics_escape(event['location'])}")
        if event["description"]:
            lines.append(f"DESCRIPTION:{ics_escape(event['description'])}")
        lines.append(f"URL:{SOURCE_URL}")
        lines.append("STATUS:CONFIRMED")
        lines.append("END:VEVENT")

    lines.append("END:VCALENDAR")
    return "\r\n".join(fold_ics_line(line) for line in lines) + "\r\n"


def fetch_html(url: str) -> tuple[str, str | None]:
    response = requests.get(
        url,
        timeout=(15, 45),
        headers={"User-Agent": "THWS-M2IV-Calendar/1.0 (+personal study timetable; contact not provided)"},
    )
    response.raise_for_status()
    if not response.encoding or response.encoding.lower() in {"iso-8859-1", "ascii"}:
        response.encoding = response.apparent_encoding or "utf-8"
    return response.text, response.url


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="public/stundenplan.ics", help="ICS output path")
    parser.add_argument("--status-output", default="public/status.json", help="JSON status output path")
    parser.add_argument("--url", default=SOURCE_URL, help="Source timetable URL")
    parser.add_argument("--input-html", help="Read HTML from a local file (for tests; no network request)")
    parser.add_argument("--min-events", type=int, default=25, help="Fail rather than publish fewer events")
    args = parser.parse_args()

    if args.input_html:
        html_text = Path(args.input_html).read_text(encoding="utf-8")
        resolved_url = args.url
    else:
        html_text, resolved_url = fetch_html(args.url)

    events, source_stand = parse_timetable(html_text)
    if len(events) < args.min_events:
        raise RuntimeError(
            f"Nur {len(events)} Termine erkannt (Mindestwert: {args.min_events}). "
            "Es wird absichtlich keine Kalenderdatei veröffentlicht, um einen unvollständigen Feed zu vermeiden."
        )

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(build_ics(events, source_stand), encoding="utf-8", newline="")

    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    status = {
        "calendar": CALENDAR_NAME,
        "source_url": resolved_url,
        "source_last_updated": source_stand,
        "last_checked_utc": now,
        "event_count": len(events),
        "first_event": events[0]["start"].isoformat() if events else None,
        "last_event": events[-1]["end"].isoformat() if events else None,
    }
    status_path = Path(args.status_output)
    status_path.parent.mkdir(parents=True, exist_ok=True)
    status_path.write_text(json.dumps(status, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(f"Quelle: {resolved_url}")
    print(f"Stand der THWS-Seite: {source_stand or 'nicht erkannt'}")
    print(f"Erkannte Termine: {len(events)}")
    print(f"ICS geschrieben: {output_path}")
    print(f"Status geschrieben: {status_path}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:  # Clear workflow error without a silent or partial publication.
        print(f"FEHLER: {exc}", file=sys.stderr)
        raise SystemExit(1)
